"""Weekly: re-rank the listed-stocks classification file by popularity.

``options-scanner/data/us_listed_stocks_classification.csv`` is a roster of US
listed stocks with their industry and sub-industry. This gives every row a
popularity score and its rank inside its ``Industry`` and, separately, inside its
``Sub_Industry`` (the two are different classifications and do not nest).

**The score** is a blend of two percentiles taken across the whole file, 0..100:

* average DOLLAR volume: Schwab's 3-month average share volume (the 10-day
  average where there is no 3-month figure) times the previous close;
* market cap: Schwab's, with the file's own ``Market_Cap_USD`` where Schwab has
  none (``[inputs] market_cap`` can put the file first).

A figure that is missing scores 0 for its half. Rank 1 is the highest score in
the group; a row whose group is blank gets no rank in that grouping.

**The file is a roster a person curated, and the tool owns only RANK_COLUMNS.**
It never adds, drops or reorders a row and never rewrites another column: a
symbol Schwab no longer knows keeps its row, with empty figures and a score of 0.

**A run short of data changes nothing and exits 1.** If Schwab answers for fewer
than ``[safety] min_coverage`` of the symbols (the proxy stumbled, or the 7-day
sign-in lapsed over the weekend) the file is left exactly as it was, so last
week's ranks stand and the failure shows in ``systemctl --user --failed``.

Scheduled by ``trading-<env>-stock-rank.timer``, generated by
``deploy/systemd/generate_units.py`` from ``[slots.stock_rank]`` in
``config/sessions.toml`` (Saturday). Settings: ``config/listed_stocks.toml``,
read at run time. About 100 paced proxy calls, a few minutes.

Usage:
    .venv/bin/python tools/rank_listed_stocks.py [--dry-run]
"""
import argparse
import collections
import csv
import io
import os
import pathlib
import sys
import time

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from repo_paths import LISTED_STOCKS_CSV, LISTED_STOCKS_TOML, PROXY_URL  # noqa: E402
from shared.config_toml import toml_loader                              # noqa: E402
from shared.numeric import parsed_finite                                # noqa: E402

# The columns this tool owns, in the order they are written after the file's own.
RANK_COLUMNS = ("Avg_Volume", "Avg_Volume_Basis", "Price_USD", "Avg_Dollar_Volume_USD",
                "Market_Cap_Used_USD", "Popularity_Score",
                "Industry_Rank", "Industry_Count",
                "Sub_Industry_Rank", "Sub_Industry_Count")

# config/listed_stocks.toml's built-in defaults - the file only overrides.
DEFAULTS = {
    "blend": {"dollar_volume_weight": 0.5},
    "inputs": {"market_cap": "schwab"},
    "fetch": {"fundamentals_batch": 100, "quotes_batch": 150, "pause_sec": 2.0},
    "safety": {"min_coverage": 0.90},
}
load_config, reset_config = toml_loader(LISTED_STOCKS_TOML, DEFAULTS,
                                        label="listed_stocks.toml")

CALLER = "rank_listed_stocks"


def positive(value) -> float:
    """``value`` as a float above zero, else 0.0 ("no usable figure")."""
    out = parsed_finite(value)
    return out if out is not None and out > 0 else 0.0


def percentiles(values):
    """Each value's mid-rank percentile (0..100) among the values above zero.

    Zero means "missing": it scores 0.0 and is not part of the field the others
    are measured against. Equal values share one percentile."""
    present = sorted(v for v in values if v > 0)
    first, last = {}, {}
    for i, v in enumerate(present):
        first.setdefault(v, i)
        last[v] = i
    n = len(present)
    return [100.0 * ((first[v] + last[v]) / 2 + 0.5) / n if v > 0 else 0.0
            for v in values]


def _whole(value) -> str:
    return str(int(round(value))) if value else ""


def _price(value) -> str:
    return f"{value:.6f}".rstrip("0").rstrip(".") if value else ""


def rank_rows(rows, fundamentals, prices, *, volume_weight=0.5, market_cap="schwab"):
    """``rows`` with RANK_COLUMNS filled in. Pure; returns new dicts.

    ``fundamentals`` is ``{symbol: {avg3MonthVolume, avg10DaysVolume, marketCap}}``
    and ``prices`` is ``{symbol: price}``. Row order and every other column are
    kept; RANK_COLUMNS already present are replaced, never duplicated."""
    shares, basis, price, dollars, caps = [], [], [], [], []
    for row in rows:
        fund = fundamentals.get(row["Symbol"]) or {}
        v3, v10 = positive(fund.get("avg3MonthVolume")), positive(fund.get("avg10DaysVolume"))
        px = positive(prices.get(row["Symbol"]))
        own, schwab = positive(row.get("Market_Cap_USD")), positive(fund.get("marketCap"))
        shares.append(v3 or v10)
        basis.append("3M" if v3 else "10D" if v10 else "")
        price.append(px)
        dollars.append((v3 or v10) * px)
        caps.append((own or schwab) if market_cap == "file" else (schwab or own))

    weight = min(1.0, max(0.0, float(volume_weight)))
    scores = [round(weight * d + (1.0 - weight) * c, 2)
              for d, c in zip(percentiles(dollars), percentiles(caps))]

    def within(column):
        groups = collections.defaultdict(list)
        for i, row in enumerate(rows):
            if (row.get(column) or "").strip():
                groups[row[column]].append(i)
        place = {}
        for members in groups.values():
            order = sorted(members, key=lambda i: (-scores[i], -caps[i], -dollars[i],
                                                   rows[i]["Symbol"]))
            for pos, i in enumerate(order, 1):
                place[i] = (str(pos), str(len(members)))
        return place

    industry, sub = within("Industry"), within("Sub_Industry")
    out = []
    for i, row in enumerate(rows):
        new = {k: v for k, v in row.items() if k not in RANK_COLUMNS}
        new.update(zip(RANK_COLUMNS, (
            _whole(shares[i]), basis[i], _price(price[i]), _whole(dollars[i]),
            _whole(caps[i]), f"{scores[i]:.2f}",
            *industry.get(i, ("", "")), *sub.get(i, ("", "")))))
        out.append(new)
    return out


def _batches(items, size):
    size = max(1, int(size))
    return [items[i:i + size] for i in range(0, len(items), size)]


def fetch_fundamentals(symbols, get, *, batch, pause, sleep=time.sleep):
    """``{symbol: fundamental}`` from the proxy's ``/instruments``.

    ⚠ A class share (``BRK.B``) is asked for ALONE: the proxy rewrites it to
    Schwab's ``BRK/B`` only when it is the whole ``symbol`` parameter, so in a
    comma list Schwab does not recognise it and the symbol silently goes
    missing. A call that fails costs its own symbols and nothing else; the
    caller decides whether what arrived is enough."""
    plain = [s for s in symbols if "." not in s]
    asks = _batches(plain, batch) + [[s] for s in symbols if "." in s]
    out = {}
    for ask in asks:
        data = get("/instruments", {"symbol": ",".join(ask), "projection": "fundamental"})
        for ins in (data or {}).get("instruments") or []:
            if isinstance(ins, dict) and ins.get("symbol"):
                out[ins["symbol"]] = ins.get("fundamental") or {}
        sleep(pause)
    return out


def fetch_prices(symbols, get, *, batch, pause, sleep=time.sleep):
    """``{symbol: price}`` from the proxy's ``/quotes``: the previous close, or
    the last trade where there is no close. A symbol with neither is omitted."""
    out = {}
    for ask in _batches(list(symbols), batch):
        data = get("/quotes", {"symbols": ",".join(ask)}) or {}
        for symbol, body in data.items():
            quote = body.get("quote") if isinstance(body, dict) else None
            if symbol == "errors" or not isinstance(quote, dict):
                continue
            px = positive(quote.get("closePrice")) or positive(quote.get("lastPrice"))
            if px:
                out[symbol] = px
        sleep(pause)
    return out


def _proxy_get(path, params):
    """One GET to the proxy on loopback -> its JSON, or None. Never raises."""
    import json
    import urllib.parse
    import urllib.request
    url = f"{PROXY_URL}{path}?{urllib.parse.urlencode(params)}"
    try:
        req = urllib.request.Request(url, headers={"X-Caller": CALLER})
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read().decode("utf-8"))
    except Exception:  # noqa: BLE001 - a failed call is a missing batch, counted below.
        return None


def _under_pytest():
    return bool(os.environ.get("PYTEST_CURRENT_TEST"))


def _write(path, columns, rows):
    """Replace ``path`` in one step, so a reader never sees half a file."""
    buf = io.StringIO(newline="")
    writer = csv.DictWriter(buf, columns, lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    tmp = path.with_name(path.name + ".tmp")
    try:
        tmp.write_bytes(buf.getvalue().encode("utf-8"))
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def run(csv_path=None, *, get=None, sleep=time.sleep, log=print, dry_run=False):
    """Re-rank the file in place. Returns the exit status: 0, or 1 when the run
    could not be trusted and the file was left as it was.

    ⚠ ``csv_path`` is resolved at CALL time, and with none given the run is
    skipped under pytest, so a test can never reach the live file."""
    if csv_path is None and _under_pytest():
        log("skipped: no csv_path under pytest")
        return 0
    path = pathlib.Path(csv_path or LISTED_STOCKS_CSV)
    try:
        with open(path, newline="", encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
    except OSError as e:
        log(f"cannot read {path}: {e}")
        return 1
    if not rows or "Symbol" not in rows[0]:
        log(f"{path} has no rows with a Symbol column - nothing to rank")
        return 1

    cfg = load_config()
    get = get or _proxy_get
    symbols = [r["Symbol"] for r in rows]
    pause = cfg["fetch"]["pause_sec"]
    fundamentals = fetch_fundamentals(symbols, get, batch=cfg["fetch"]["fundamentals_batch"],
                                      pause=pause, sleep=sleep)
    prices = fetch_prices(symbols, get, batch=cfg["fetch"]["quotes_batch"],
                          pause=pause, sleep=sleep)

    floor = cfg["safety"]["min_coverage"]
    have = {"fundamentals": sum(1 for s in symbols if s in fundamentals) / len(symbols),
            "prices": sum(1 for s in symbols if s in prices) / len(symbols)}
    log(f"{len(symbols)} symbols; Schwab answered for "
        f"{have['fundamentals']:.1%} (fundamentals) and {have['prices']:.1%} (prices)")
    short = [name for name, share in have.items() if share < floor]
    if short:
        log(f"REFUSED: {' and '.join(short)} below the {floor:.0%} floor "
            f"([safety] min_coverage) - the file is left as it was")
        return 1

    ranked = rank_rows(rows, fundamentals, prices,
                       volume_weight=cfg["blend"]["dollar_volume_weight"],
                       market_cap=cfg["inputs"]["market_cap"])
    no_volume = sum(1 for r in ranked if not r["Avg_Dollar_Volume_USD"])
    no_cap = sum(1 for r in ranked if not r["Market_Cap_Used_USD"])
    log(f"ranked {len(ranked)} rows; {no_volume} with no dollar volume, "
        f"{no_cap} with no market cap")
    if dry_run:
        log("dry run: nothing written")
        return 0
    _write(path, list(ranked[0]), ranked)
    log(f"wrote {path}")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true",
                    help="fetch and rank, report, change nothing")
    args = ap.parse_args()
    raise SystemExit(run(dry_run=args.dry_run))


if __name__ == "__main__":
    main()
